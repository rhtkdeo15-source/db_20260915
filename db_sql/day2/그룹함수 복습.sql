-- 그룹함수
-- AVG, MAX, MIN, COUNT, SUM

-- 전제 학생들 평균 키
SELECT 
    AVG(STU_HEIGHT)
FROM STUDENT;

--학과별 학생들 전체 키 평균
SELECT 
    STU_DEPT,
    AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT;

--170이상만 대상으로
SELECT 
    STU_DEPT,
    AVG(STU_HEIGHT)
FROM STUDENT
WHERE STU_HEIGHT >= 170
GROUP BY STU_DEPT;

-- 평균키가 175이상인 학과만
SELECT 
    STU_DEPT,
    AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT
HAVING STU_HEIGHT >= 175;

-- COUNT는 컬럼명을 넣었을때 NULL값은 제외하고 카운트
SELECT 
COUNT(*),
COUNT(STU_NO),
COUNT(STU_HEIGHT)
FROM STUDENT;

-- 조인 INNER

-- 학번, 이름, 점수, 과목명
SELECT 
    S.STU_NO,STU_NAME,STU_DEPT,ENR_GRADE,SUB_NAME
FROM STUDENT S
INNER JOIN ENROL E ON E.STU_NO = S.STU_NO
INNER JOIN SUBJECT SUB ON E.SUB_NO = SUB.SUB_NO;

