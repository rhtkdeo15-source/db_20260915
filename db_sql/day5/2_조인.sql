-- STU, 학번 이름, 전공학과, 부전공학과 출력
SELECT 
    STUNO, NAME, D1.DNAME, NVL(D2.DNAME, '부전공없음')
FROM STU S
INNER JOIN DEPARTMENT D1 ON S.DEPTNO1 = D1.DEPTNO
LEFT JOIN DEPARTMENT D2 ON S.DEPTNO2 = D2.DEPTNO;

-- STUDENT, ENROL
-- 학번, 이름, 시험본 개수 출력. 단, 시험을 안본 학생은 0으로 출력
SELECT * FROM STUDENT;
SELECT * FROM ENROL;

SELECT 
    S.STU_NO, STU_NAME,
    COUNT(ENR_GRADE) 
FROM STUDENT S
LEFT JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY S.STU_NO, STU_NAME;

-- 학생들의 평균 점수를 기준으로 순위 매기기
SELECT 
    S.STU_NO, STU_NAME, AVG(ENR_GRADE) 평균점수,
    RANK() OVER(ORDER BY AVG(ENR_GRADE) DESC) RANK
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY S.STU_NO, STU_NAME;





















