-- 교수들이 속한 대학
SELECT 
    P.NAME, D1.DNAME, D2.DNAME, D3.DNAME
FROM PROFESSOR P
INNER JOIN DEPARTMENT D1 ON P.DEPTNO = D1.DEPTNO
INNER JOIN DEPARTMENT D2 ON D1.PART = D2.DEPTNO
INNER JOIN DEPARTMENT D3 ON D2.PART = D3.DEPTNO;

-- EMP 테이블에서 본인 급여 등급 보다 높은 급여 등급을 가진 사람수 구하기
-- 사번 이름 급여등급 사람 수 구하기
SELECT 
    EMPNO, ENAME,
    RANK() OVER(ORDER BY GRADE DESC) -1 AS사람수, GRADE
FROM EMP E
INNER JOIN SALGRADE S ON E.SAL BETWEEN S.LOSAL AND S.HISAL;

