-- VIEW에서 수정이 가능한 경우(밑에 4개 다 만족 해야함)
-- 1. 읽기 전용 옵션 없을 때(WITH READ ONLY 없을때)
-- 2. JOIN이 없을 때
-- 3. GROUP함수 없을때
-- 4. DISTINCT 없을때
-- # VIEW는 웬만하면 READ ONLY옵션 적용하는게 좋다

SELECT
    DISTINCT STU_NO, ENR_GRADE --DISTINCT 모든컬럼이 동일할 때 중복제거 가능
FROM ENROL;

SELECT * FROM STUDENT;
