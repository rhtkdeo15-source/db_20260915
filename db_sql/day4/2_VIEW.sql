-- VIEW
SELECT * FROM EMP;

DROP VIEW EMP_VIEW;

CREATE OR REPLACE VIEW EMP_VIEW AS
SELECT EMPNO, ENAME, JOB, DNAME, LOC
FROM EMP E
INNER JOIN DEPT D ON E.DEPTNO = D.DEPTNO
WITH READ ONLY -- 읽기전용
;

